-- 1. PEOPLE AND ACCESS
-- ------------------------------------------------------------
CREATE TABLE care_staff (
    staff_id       INT AUTO_INCREMENT PRIMARY KEY,
    full_name      VARCHAR(100) NOT NULL,
    staff_role     ENUM('Doctor','Nurse') NOT NULL,
    specialization VARCHAR(100),
    phone          VARCHAR(20),
    email          VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE patients (
    patient_id         INT AUTO_INCREMENT PRIMARY KEY,
    full_name          VARCHAR(100) NOT NULL,
    phone              VARCHAR(20),
    date_of_birth      DATE,
    preferred_language ENUM('en','hi') NOT NULL DEFAULT 'en',
    consent_status     ENUM('Granted','Pending','Withdrawn') NOT NULL DEFAULT 'Pending',
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A caregiver is contacted ONLY when consent_granted = TRUE (privacy by design).
CREATE TABLE caregivers (
    caregiver_id    INT AUTO_INCREMENT PRIMARY KEY,
    patient_id      INT NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    phone           VARCHAR(20) NOT NULL,
    relationship    VARCHAR(40),
    consent_granted BOOLEAN NOT NULL DEFAULT FALSE,
    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_caregiver_patient FOREIGN KEY (patient_id)
        REFERENCES patients(patient_id) ON DELETE CASCADE
);

-- Exactly one identity column must be filled, matching the role.
CREATE TABLE user_accounts (
    account_id    INT AUTO_INCREMENT PRIMARY KEY,
    email         VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    account_role  ENUM('Patient','Caregiver','Doctor','Nurse') NOT NULL,
    patient_id    INT NULL,
    caregiver_id  INT NULL,
    staff_id      INT NULL,
    CONSTRAINT fk_account_patient   FOREIGN KEY (patient_id)   REFERENCES patients(patient_id),
    CONSTRAINT fk_account_caregiver FOREIGN KEY (caregiver_id) REFERENCES caregivers(caregiver_id),
    CONSTRAINT fk_account_staff     FOREIGN KEY (staff_id)     REFERENCES care_staff(staff_id),
    CONSTRAINT chk_account_identity CHECK (
        (account_role = 'Patient'   AND patient_id   IS NOT NULL AND caregiver_id IS NULL AND staff_id IS NULL) OR
        (account_role = 'Caregiver' AND caregiver_id IS NOT NULL AND patient_id   IS NULL AND staff_id IS NULL) OR
        (account_role IN ('Doctor','Nurse') AND staff_id IS NOT NULL AND patient_id IS NULL AND caregiver_id IS NULL)
    )
);

-- ------------------------------------------------------------
-- 2. DISCHARGE PLAN + DOCUMENTS FOR RAG
-- ChromaDB stores the vectors. MySQL stores the metadata and the chunk text,
-- so every AI answer can show exactly which source chunk it used.
-- ------------------------------------------------------------
CREATE TABLE discharge_records (
    discharge_id       INT AUTO_INCREMENT PRIMARY KEY,
    patient_id         INT NOT NULL,
    attending_staff_id INT NOT NULL,
    discharge_date     DATE NOT NULL,
    condition_summary  VARCHAR(255),
    instructions       TEXT,
    follow_up_due      DATE,
    CONSTRAINT fk_discharge_patient FOREIGN KEY (patient_id)
        REFERENCES patients(patient_id) ON DELETE CASCADE,
    CONSTRAINT fk_discharge_staff FOREIGN KEY (attending_staff_id)
        REFERENCES care_staff(staff_id),
    CONSTRAINT chk_followup_after_discharge CHECK (follow_up_due IS NULL OR follow_up_due >= discharge_date)
);

CREATE TABLE discharge_documents (
    document_id       INT AUTO_INCREMENT PRIMARY KEY,
    discharge_id      INT NOT NULL,
    file_name         VARCHAR(200) NOT NULL,
    uploaded_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
