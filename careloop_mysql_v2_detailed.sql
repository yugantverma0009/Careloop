-- 8. VIEWS FOR DASHBOARDS
-- ------------------------------------------------------------
CREATE VIEW v_latest_risk AS
SELECT x.patient_id, x.computed_at, x.risk_score,
       CASE WHEN x.risk_score >= 60 THEN 'High'
            WHEN x.risk_score >= 30 THEN 'Moderate'
            ELSE 'Low' END AS risk_level,
       x.contributing_factors
FROM (
    SELECT rs.patient_id, rs.computed_at, rs.risk_score, rs.contributing_factors,
           ROW_NUMBER() OVER (PARTITION BY rs.patient_id
                              ORDER BY rs.computed_at DESC, rs.snapshot_id DESC) AS rn
    FROM risk_snapshots rs
) x
WHERE x.rn = 1;

CREATE VIEW v_triage_board AS
SELECT p.patient_id, p.full_name AS patient_name,
       f.flag_id, f.severity, f.source_type, f.reason, f.status,
       f.created_at AS flagged_at,
       TIMESTAMPDIFF(MINUTE, f.created_at, NOW()) AS minutes_open,
       lr.risk_score, lr.risk_level
FROM flags f
JOIN patients p ON p.patient_id = f.patient_id
LEFT JOIN v_latest_risk lr ON lr.patient_id = p.patient_id
WHERE f.status IN ('Open','Acknowledged');

CREATE VIEW v_latest_sensor_readings AS
SELECT x.patient_id, p.full_name AS patient_name, x.measurement_type,
       x.measurement_value, x.unit, x.measured_at, x.quality_status, x.device_id
FROM (
    SELECT sr.*,
           ROW_NUMBER() OVER (PARTITION BY sr.patient_id, sr.measurement_type
                              ORDER BY sr.measured_at DESC) AS rn
    FROM sensor_readings sr
) x
JOIN patients p ON p.patient_id = x.patient_id
WHERE x.rn = 1;

-- Percentages are based on patient SELF-REPORTED confirmations only.
CREATE VIEW v_medication_adherence AS
SELECT p.patient_id, p.full_name AS patient_name,
       COUNT(ml.medication_log_id) AS scheduled_events,
       COALESCE(SUM(ml.status = 'Taken_Confirmed'), 0) AS taken_confirmed,
       COALESCE(SUM(ml.status = 'Skipped'), 0)         AS marked_skipped,
       COALESCE(SUM(ml.status = 'Missed'), 0)          AS no_confirmation_missed,
       COALESCE(SUM(ml.status = 'Unconfirmed'), 0)     AS still_pending,
       ROUND(100 * SUM(ml.status = 'Taken_Confirmed')
             / NULLIF(SUM(ml.status <> 'Unconfirmed'), 0), 1) AS self_reported_taken_pct
FROM patients p
JOIN prescriptions pr ON pr.patient_id = p.patient_id
LEFT JOIN medication_logs ml ON ml.prescription_id = pr.prescription_id
GROUP BY p.patient_id, p.full_name;

-- Missing data is shown explicitly. It is never treated as a normal reading.
CREATE VIEW v_device_status AS
SELECT d.device_id, d.patient_id, p.full_name AS patient_name, d.device_type,
       d.last_seen_at, d.expected_interval_minutes,
       TIMESTAMPDIFF(MINUTE, d.last_seen_at, NOW()) AS minutes_since_last_seen,
       CASE WHEN d.last_seen_at IS NULL THEN 'Never_Connected'
            WHEN TIMESTAMPDIFF(MINUTE, d.last_seen_at, NOW()) > 2 * d.expected_interval_minutes THEN 'Missing_Data'
            ELSE 'Online' END AS connectivity_status
FROM devices d
JOIN patients p ON p.patient_id = d.patient_id;

CREATE VIEW v_pending_followups AS
