    vector_collection VARCHAR(100),
    CONSTRAINT fk_document_discharge FOREIGN KEY (discharge_id)
        REFERENCES discharge_records(discharge_id) ON DELETE CASCADE
);

CREATE TABLE document_chunks (
    chunk_id    BIGINT AUTO_INCREMENT PRIMARY KEY,
